dashboard_ui <- function() {
  fluidPage(
    titlePanel("Portfolio Risk & Stress Testing Engine"),
    sidebarLayout(
      sidebarPanel(width = 3,
        h4("Portfolio settings"),
      selectInput("portfolio_source", "Holdings", c("Sample Portfolio", "Upload CSV")),
      conditionalPanel("input.portfolio_source == 'Upload CSV'",
        fileInput("portfolio_file", "Portfolio CSV", accept = ".csv")),
      selectInput("data_mode", "Price source", c("Yahoo Finance" = "yahoo", "Synthetic demonstration" = "demo")),
      dateRangeInput("market_dates", "Observation window", start = Sys.Date() - 3 * 365, end = Sys.Date()),
      actionButton("load", "Load / refresh prices"),
      p("Prices load on request. All amounts assume USD-listed instruments."),
      hr(),
      selectInput("confidence", "One-day confidence", c("95%" = .95, "97.5%" = .975, "99%" = .99), selected = .99),
      numericInput("simulations", "Monte Carlo draws", 20000, min = 10000, max = 200000, step = 10000),
      numericInput("seed", "Simulation seed", 42, min = 0, max = 1000000),
      numericInput("window", "Backtest window (observations)", 250, min = 20, max = 1000),
      hr(), p("Long-only  /  Equity & ETF  /  1-day risk horizon")
    ),
      mainPanel(width = 9,
    uiOutput("data_status"),
    tabsetPanel(
      tabPanel("Overview", uiOutput("overview_cards"),
        fluidRow(column(6, h4("Portfolio return history"), plotly::plotlyOutput("portfolio_plot")),
          column(6, h4("Capital allocation"), plotly::plotlyOutput("weights_plot"))),
        p("Historical returns use fixed valuation-date weights, rebalanced daily. Daily P&L is a modeled last-observation amount, not an accounting P&L.")),
      tabPanel("Portfolio", uiOutput("portfolio_summary"), DT::DTOutput("portfolio_table")),
      tabPanel("Market Data",
        selectInput("selected_ticker", "Asset", choices = NULL),
        DT::DTOutput("market_table"),
        radioButtons("return_type", "Return type", c("Simple" = "simple", "Log" = "log"), inline = TRUE),
        plotly::plotlyOutput("asset_plot"), DT::DTOutput("returns_table")),
      tabPanel("Risk Metrics", DT::DTOutput("metrics_table"),
        h4("Volatility contributions"), DT::DTOutput("contributions"),
        p("Annual return = exp(252 * mean(log(1 + daily return))) - 1. Annual volatility = daily sample standard deviation * sqrt(252). This assumes stationary returns and ignores serial dependence.")),
      tabPanel("VaR & ES", DT::DTOutput("risk_table"), textOutput("var_interpretation"),
        plotly::plotlyOutput("var_plot"),
        p("Historical VaR uses the empirical lower-tail quantile without a normality assumption. Historical ES is the mean loss at or beyond that threshold (ties included). Normal parametric VaR and ES can underestimate fat tails. Negative risk values represent a gain threshold; values are not clamped to zero.")),
      tabPanel("Monte Carlo", textOutput("simulation_note"), DT::DTOutput("mc_table"),
        plotly::plotlyOutput("mc_plot"),
        p("Correlated normal asset returns are simulated from the sample mean vector and covariance matrix. A symmetric eigen square root supports singular covariance. This model has unbounded tails, can generate returns below -100%, and is not a full repricing model.")),
      tabPanel("Stress Testing",
        selectInput("scenario", "Hypothetical scenario", c(stress_scenarios()$Scenario, "Custom Scenario")),
        conditionalPanel("input.scenario == 'Custom Scenario'",
          sliderInput("equity_shock", "Equity shock (%)", -100, 100, -20),
          sliderInput("etf_shock", "ETF shock (%)", -100, 100, -15)),
        p("All scenarios are hypothetical. GFC/COVID/EM labels indicate historical-style hypothetical scenarios, not historical replays. Rate, FX and high-volatility labels use static Equity/ETF price shocks; they do not model duration, currency exposures or a volatility process."),
        uiOutput("stress_cards"), plotly::plotlyOutput("stress_plot"),
        DT::DTOutput("stress_holdings"), DT::DTOutput("stress_classes"),
        h4("Scenario comparison"), DT::DTOutput("scenarios_table"),
        h4("Equity price sensitivity"),
        sliderInput("sensitivity", "Symmetric equity shock (%)", 1, 30, 5),
        p("ETF values are held constant in this equity-only sensitivity."),
        DT::DTOutput("sensitivity_table"), DT::DTOutput("sensitivity_total")),
      tabPanel("Correlation", plotly::plotlyOutput("heatmap"),
        textOutput("volatility_check"), h4("Correlation"), DT::DTOutput("correlation_table"),
        h4("Daily covariance"), DT::DTOutput("covariance_table"),
        p("Less-than-perfect correlation can reduce portfolio volatility. Correlations can rise during market stress, weakening diversification when it is most needed. Constant-price assets have undefined correlations (shown as missing).")),
      tabPanel("Backtesting", DT::DTOutput("backtest_summary"), plotly::plotlyOutput("backtest_plot"),
        p("Each forecast uses only the previous rolling window, then compares with the next observed loss. Fixed current portfolio weights make this a diagnostic of today's portfolio, not an investable historical strategy. Kupiec tests H0: exception probability = 1 - confidence. Its likelihood ratio compares this rate with the observed rate; a small p-value suggests poor coverage, but the test does not assess exception independence. Small samples weaken the asymptotic test."),
        DT::DTOutput("backtest_detail")),
      tabPanel("Reports",
        h3("Management risk report"), p("Export the active analysis, holdings, model assumptions, stress results, correlation, backtesting and charts."),
        downloadButton("report_html", "Download HTML report"),
        downloadButton("report_pdf", "Download PDF report"),
        textOutput("report_capabilities"),
        hr(), downloadButton("holdings_csv", "Download valued holdings CSV"))
    )
      )
    )
  )
}

